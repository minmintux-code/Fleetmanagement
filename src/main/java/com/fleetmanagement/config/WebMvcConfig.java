package com.fleetmanagement.config;

import org.springframework.context.annotation.Configuration;
import org.springframework.web.servlet.config.annotation.CorsRegistry;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

/**
 * WebMvcConfig - CORS configuration for development.
 * Auth interceptor is disabled until JWT is implemented.
 */
@Configuration
public class WebMvcConfig implements WebMvcConfigurer {

    // AuthInterceptor is intentionally NOT registered during development.
    // All /api/** routes are open. Re-enable when JWT is ready.

    @Override
    public void addCorsMappings(CorsRegistry registry) {
        registry.addMapping("/**")
                .allowedOriginPatterns("http://localhost:3000", "http://localhost:5173", "http://127.0.0.1:3000")
                .allowedMethods("GET", "POST", "PUT", "DELETE", "OPTIONS", "PATCH")
                .allowedHeaders("*")
                .allowCredentials(true)
                .maxAge(3600);
    }
}
